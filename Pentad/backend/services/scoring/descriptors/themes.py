def theme_of(name: str | None) -> str:
    """按名称关键词归到可聚合的主题; 认不出时退回 ETF 前缀。"""
    if not name:
        return "其他"
    for theme, keywords in THEME_RULES:
        if any(k in name for k in keywords):
            return theme
    prefix = name.split("ETF")[0].strip()
    return prefix[:10] or "其他"
